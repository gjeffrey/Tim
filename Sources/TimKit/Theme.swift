import Foundation
import CoreText

/// A typeface the editor can offer. Curated Google Fonts (self-served via
/// the fonts.googleapis.com CSS API for now; Fontsource self-hosting is the
/// planned upgrade) plus user-imported font files.
public struct FontOption: Identifiable, Hashable {
    public var id: String { name }
    public let name: String        // display name in the picker
    public let family: String      // CSS font-family value
    public let fallback: String    // generic fallback: sans-serif / serif / monospace
    public let googleQuery: String?  // e.g. "Inter:wght@400;700" — nil for system/custom
    public let faceFile: String?     // site-relative font file for @font-face — custom fonts

    public init(name: String, family: String, fallback: String, googleQuery: String? = nil, faceFile: String? = nil) {
        self.name = name
        self.family = family
        self.fallback = fallback
        self.googleQuery = googleQuery
        self.faceFile = faceFile
    }
}

