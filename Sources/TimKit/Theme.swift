public struct TimTheme {
    public var headingFont: FontOption
    public var bodyFont: FontOption
    public var accentHex: String   // "#0A84FF"

    public init(headingFont: FontOption = FontCatalog.system, bodyFont: FontOption = FontCatalog.system, accentHex: String = "#0A84FF") {
        self.headingFont = headingFont
        self.bodyFont = bodyFont
        self.accentHex = accentHex
    }
}

/// Writes the theme as a Tim-owned stylesheet in the project and makes sure
/// the site's layout links it. The file is wholly regenerated on every
/// apply — Tim owns it, the rest of the site's CSS stays untouched.
public enum ThemeManager {
    public static let stylesheetName = "tim-theme.css"

    @discardableResult
    public static func apply(_ theme: TimTheme, projectPath: String) throws -> String {
        let publicDir = (projectPath as NSString).appendingPathComponent("public")
        try FileManager.default.createDirectory(atPath: publicDir, withIntermediateDirectories: true)
        let cssPath = (publicDir as NSString).appendingPathComponent(stylesheetName)
        try generateCSS(theme).write(toFile: cssPath, atomically: true, encoding: .utf8)
        let linked = try ensureLinked(projectPath: projectPath)
        return "Theme written to public/\(stylesheetName)" + (linked ? " and linked in the layout" : "")
    }

    static func generateCSS(_ theme: TimTheme) -> String {
        var css = "/* Generated by Tim — Tim rewrites this file on every theme change. */\n"

        let queries = [theme.headingFont.googleQuery, theme.bodyFont.googleQuery]
            .compactMap { $0 }
        if !queries.isEmpty {
            let families = Array(Set(queries)).sorted().map { "family=\($0)" }.joined(separator: "&")
            css += "@import url('https://fonts.googleapis.com/css2?\(families)&display=swap');\n"
        }
        for font in [theme.headingFont, theme.bodyFont] {
            if let face = font.faceFile {
                css += """
                @font-face {
                  font-family: \(font.family);
                  src: url('\(face)');
                  font-display: swap;
                }\n
                """
            }
        }

        css += """
        :root {
          --tim-font-heading: \(theme.headingFont.family), \(theme.headingFont.fallback);
          --tim-font-body: \(theme.bodyFont.family), \(theme.bodyFont.fallback);
          --tim-accent: \(theme.accentHex);
        }
        body { font-family: var(--tim-font-body); }
        h1, h2, h3, h4, h5, h6 { font-family: var(--tim-font-heading); }
        a { color: var(--tim-accent); }

        /* Canvas layout: a true two-axis grid (Fluid Engine-style) — 24
           columns, fixed-unit rows. Objects own explicit cell rectangles
           (grid-area), so placement feels freeform but is grid-quantized.
           On small screens the grid collapses to a single column in
           reading order — responsive by construction. */
        .tim-canvas {
          display: grid;
          grid-template-columns: repeat(24, 1fr);
          grid-auto-rows: 32px;
          gap: 16px;
          align-items: stretch;
          box-sizing: border-box;
          /* The canvas is the surface, never a guest in an article column:
             break out to the full viewport, content capped at ~1320px. */
          width: 100vw;
          margin-left: calc(50% - 50vw);
          margin-right: calc(50% - 50vw);
          padding: 48px max(32px, calc(50vw - 660px));
          min-height: 70vh;
        }
        .tim-object { min-width: 0; }
        .tim-text { min-height: 1em; outline: none; padding: 2px 4px; }
        .tim-canvas img.tim-object { width: 100%; height: 100%; object-fit: cover; display: block; }
        .tim-canvas video.tim-object { width: 100%; display: block; }
        .tim-canvas audio.tim-object { width: 100%; }
        @media (max-width: 700px) {
          .tim-canvas { grid-template-columns: 1fr; grid-auto-rows: auto; padding: 24px 16px; min-height: 0; }
          .tim-canvas > .tim-object { grid-area: auto !important; }
        }

        /* Global text styles — restyle these here, every page follows. */
        .tim-style-title { font-family: var(--tim-font-heading); font-size: 2.5rem; font-weight: 700; line-height: 1.15; }
        .tim-style-heading { font-family: var(--tim-font-heading); font-size: 1.6rem; font-weight: 700; line-height: 1.25; }
        .tim-style-subheading { font-family: var(--tim-font-heading); font-size: 1.25rem; font-weight: 600; line-height: 1.3; }
        .tim-style-body { font-family: var(--tim-font-body); font-size: 1rem; line-height: 1.6; }
        .tim-style-caption { font-size: 0.85rem; opacity: 0.7; line-height: 1.4; }
        """
        return css
    }

    /// Inserts the stylesheet link into the first layout's <head> if it
    /// isn't there already. Returns true if the layout references it.
    static func ensureLinked(projectPath: String) throws -> Bool {
        let layoutsDir = (projectPath as NSString).appendingPathComponent("src/layouts")
        let fm = FileManager.default
        guard let layouts = try? fm.contentsOfDirectory(atPath: layoutsDir)
            .filter({ $0.hasSuffix(".astro") }).sorted(),
              let first = layouts.first
        else { return false }

        let layoutPath = (layoutsDir as NSString).appendingPathComponent(first)
        var source = try String(contentsOfFile: layoutPath, encoding: .utf8)
        guard !source.contains(stylesheetName) else { return true }
        guard let headEnd = source.range(of: "</head>") else { return false }
        source.insert(
            contentsOf: "  <link rel=\"stylesheet\" href=\"/\(stylesheetName)\" />\n  ",
            at: headEnd.lowerBound
        )
        try source.write(toFile: layoutPath, atomically: true, encoding: .utf8)
        return true
    }

    /// Copies a font file into public/fonts/ and reads its real family
    /// name via CoreText. (woff2 conversion of ttf/otf is a later nicety —
    /// every modern browser renders ttf/otf directly.)
    public static func importCustomFont(from url: URL, projectPath: String) throws -> FontOption {
        let fontsDir = (projectPath as NSString).appendingPathComponent("public/fonts")
        try FileManager.default.createDirectory(atPath: fontsDir, withIntermediateDirectories: true)
        let destination = (fontsDir as NSString).appendingPathComponent(url.lastPathComponent)
        if FileManager.default.fileExists(atPath: destination) {
            try FileManager.default.removeItem(atPath: destination)
        }
        try FileManager.default.copyItem(atPath: url.path, toPath: destination)

        var family = url.deletingPathExtension().lastPathComponent
        if let descriptors = CTFontManagerCreateFontDescriptorsFromURL(url as CFURL) as? [CTFontDescriptor],
           let first = descriptors.first,
           let name = CTFontDescriptorCopyAttribute(first, kCTFontFamilyNameAttribute) as? String {
            family = name
        }
        return FontOption(
            name: "\(family) (imported)",
            family: "'\(family)'",
            fallback: "sans-serif",
            faceFile: "/fonts/\(url.lastPathComponent)"
        )
    }
}
