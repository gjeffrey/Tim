import Foundation

/// Site-wide crawler permissions, expressed the only way crawlers actually
/// check: robots.txt at the server root. Honor-system by nature — the
/// well-behaved comply; it is a request, not a lock.
public enum Robots {
    /// The known AI-training crawler user agents (2026).
    public static let aiCrawlers = [
        "GPTBot", "ClaudeBot", "anthropic-ai", "Google-Extended",
        "CCBot", "PerplexityBot", "Applebot-Extended", "Bytespider",
        "meta-externalagent", "cohere-ai", "Amazonbot", "Omgilibot"
    ]

    static let marker = "# Generated by Tim"

    public static func content(allowSearch: Bool, allowAI: Bool) -> String {
        var lines = [marker, ""]
        lines.append("User-agent: *")
        lines.append(allowSearch ? "Disallow:" : "Disallow: /")
        if allowSearch, !allowAI {
            for agent in aiCrawlers {
                lines.append("")
                lines.append("User-agent: \(agent)")
                lines.append("Disallow: /")
            }
        }
        return lines.joined(separator: "\n") + "\n"
    }

    public enum FileState {
        case none          // no robots.txt in the mirror
        case timManaged    // ours — safe to regenerate
        case foreign       // the site's own — never touch it
    }

    public static func state(inMirror folder: String) -> FileState {
        let path = (folder as NSString).appendingPathComponent("robots.txt")
        guard let text = try? String(contentsOfFile: path, encoding: .utf8) else { return .none }
        return text.hasPrefix(marker) ? .timManaged : .foreign
    }

    /// Writes (or removes the need for) the mirror's robots.txt. Returns
    /// the content when a file was written, nil when nothing changed.
    @discardableResult
    public static func write(allowSearch: Bool, allowAI: Bool, toMirror folder: String) -> String? {
        let fileState = state(inMirror: folder)
        guard fileState != .foreign else { return nil }
        // Don't create a file just to state the defaults.
        if fileState == .none, allowSearch, allowAI { return nil }
        let text = content(allowSearch: allowSearch, allowAI: allowAI)
        let path = (folder as NSString).appendingPathComponent("robots.txt")
        try? text.write(toFile: path, atomically: true, encoding: .utf8)
        return text
    }
}
